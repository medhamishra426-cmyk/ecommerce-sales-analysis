REQUIRED = {"Date", "Product", "Quantity", "Price", "Customer_ID", "Region", "Total_Sales"}

def load_data(path):
    if not os.path.exists(path):
        raise FileNotFoundError(f"{path} not found. Re-run the upload cell.")
    df = pd.read_csv(path)
    missing = REQUIRED - set(df.columns)
    if missing:
        raise ValueError(f"Missing columns: {sorted(missing)}")
    log.info(f"Loaded {len(df)} rows x {df.shape[1]} columns")
    return df

raw = load_data("data/sales_data.csv")
raw.head()

def clean_data(df):
    before = len(df)
    df = df.drop_duplicates().copy()
    df["Date"] = pd.to_datetime(df["Date"], errors="coerce")
    for col in ["Quantity", "Price", "Total_Sales"]:
        df[col] = pd.to_numeric(df[col], errors="coerce")

    invalid = df["Date"].isna() | df[["Quantity", "Price", "Total_Sales"]].isna().any(axis=1)
    if invalid.any():
        log.warning(f"Dropping {invalid.sum()} rows with invalid values")
    df = df[~invalid].copy()

    # Validation rules
    mismatch = (df["Quantity"] * df["Price"] != df["Total_Sales"]).sum()
    bad_qty = (df["Quantity"] <= 0).sum()
    log.info(f"Total_Sales mismatches: {mismatch}")
    log.info(f"Non-positive quantities: {bad_qty}")

    df["Month"] = df["Date"].dt.to_period("M").astype(str)
    log.info(f"Rows: {before} -> {len(df)} after cleaning")
    return df

df = clean_data(raw)

print(df.describe(include="all").T)
print("\nNulls per column:\n", df.isna().sum())

total_rev = df["Total_Sales"].sum()
print(f"Total revenue : {total_rev:,.0f}")
print(f"Orders        : {len(df)}")
print(f"Units sold    : {int(df['Quantity'].sum())}")
print(f"Avg order     : {df['Total_Sales'].mean():,.0f}")

by_product = (df.groupby("Product")
                .agg(Revenue=("Total_Sales", "sum"),
                     Units=("Quantity", "sum"),
                     Orders=("Total_Sales", "count"))
                .sort_values("Revenue", ascending=False))
by_product["Share %"] = (by_product["Revenue"] / total_rev * 100).round(1)

by_region = df.groupby("Region")["Total_Sales"].sum().sort_values(ascending=False)
by_month = df.groupby("Month")["Total_Sales"].sum()

by_product

def save(fig, name):
    path = f"visualizations/{name}.png"
    fig.savefig(path, bbox_inches="tight")
    print("Saved", path)

# Chart 1: Bar chart, revenue by product
